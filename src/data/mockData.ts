/**
 * Evaluates whether a vessel is trespassing or penetrating a Marine Protected Area / Sanctuary.
 */
export function isVesselSanctuaryTrespassing(v: TargetVessel): boolean {
  if (v.sanctuaryTrespass !== undefined) return v.sanctuaryTrespass;
  const text = `${v.description} ${v.infractionAlert} ${v.behavioralTrigger}`.toLowerCase();
  return (
    text.includes('sanctuary') ||
    text.includes('protected area') ||
    text.includes('marine reserve') ||
    text.includes('no-fish') ||
    text.includes('boundary crossing') ||
    text.includes('galápagos') ||
    text.includes('galapagos')
  );
}

/**
 * Evaluates whether a vessel has turned off its AIS transponder / telemetry signal (Dark Fleet).
 */
export function isVesselSignalTurnedOff(v: TargetVessel): boolean {
  if (v.signalTurnedOff !== undefined) return v.signalTurnedOff;
  if (!v.isOnline) return true;
  const text = `${v.lastAisBroadcast} ${v.description} ${v.infractionAlert} ${v.behavioralTrigger}`.toLowerCase();
  return (
    text.includes('signal off') ||
    text.includes('telemetry gap') ||
    text.includes('blackout') ||
    text.includes('dark') ||
    text.includes('cut off') ||
    text.includes('disabled') ||
    text.includes('transponder cut')
  );
}

